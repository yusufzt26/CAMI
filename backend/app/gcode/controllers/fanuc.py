def build_fanuc() -> ControllerDialect:
    return ControllerDialect(
        key="fanuc",
        name="FANUC (0i / 30i series, milling)",
        g_codes={s.code: s for s in _G},
        m_codes={s.code: s for s in _M},
        letters={
            "G": "Preparatory function",
            "M": "Miscellaneous function",
            "X": "X axis",
            "Y": "Y axis",
            "Z": "Z axis",
            "I": "Arc centre X offset",
            "J": "Arc centre Y offset",
            "K": "Arc centre Z offset / cycle repeat count",
            "R": "Arc radius / cycle R level",
            "F": "Feed rate",
            "S": "Spindle speed",
            "T": "Tool number",
            "H": "Tool length offset number",
            "D": "Cutter radius offset number",
            "P": "Dwell time / parameter",
            "Q": "Peck depth / shift amount",
            "L": "Repeat count",
        },
        foreign_axes={"A", "B", "C", "U", "V", "W"},
        peck_clearance_mm=0.5,
    )
